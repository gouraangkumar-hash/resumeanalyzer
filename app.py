"""Streamlit web application for AI Resume Analyzer.

Provides a clean, beginner-friendly interface to upload a resume PDF,
input a job description, and view rubric-based analysis generated by
a two-stage LangChain + Google Gemini prompt chain.
"""

import os
import streamlit as st

from src.pdf_parser import extract_text_from_pdf
from src.analyzer import analyze_resume
from src.schemas import ResumeAnalysisResult

# ---------------------------------------------------------------------------
# Page Configuration
# ---------------------------------------------------------------------------
st.set_page_config(
    page_title="AI Resume Analyzer",
    page_icon="📄",
    layout="wide",
)

# ---------------------------------------------------------------------------
# Main Header
# ---------------------------------------------------------------------------
st.title("📄 AI Resume Analyzer")
st.markdown(
    "Evaluate candidate resumes against specific job descriptions using **LangChain** "
    "and **Google Gemini**."
)

st.info(
    "💡 **Disclaimer:** The match score and feedback generated by this application "
    "are heuristic AI estimates. This tool does **not** simulate proprietary ATS algorithms "
    "and does **not** predict actual hiring or interview decisions.",
    icon="ℹ️",
)

# ---------------------------------------------------------------------------
# Input Section: Resume PDF & Job Description Text
# ---------------------------------------------------------------------------
col1, col2 = st.columns([1, 1], gap="medium")

with col1:
    st.subheader("1. Upload Candidate Resume (PDF)")
    uploaded_file = st.file_uploader(
        "Select a text-based PDF resume",
        type=["pdf"],
        help="Only text-selectable PDFs are supported. Scanned/image-only PDFs will be rejected.",
    )
    if uploaded_file:
        st.success(f"Loaded: `{uploaded_file.name}` ({uploaded_file.size / 1024:.1f} KB)")

with col2:
    st.subheader("2. Paste Job Description (JD)")
    jd_input = st.text_area(
        "Paste target job description text here:",
        height=220,
        placeholder="Paste role requirements, responsibilities, and qualifications...",
    )
    if jd_input:
        st.caption(f"Character count: {len(jd_input):,} chars")

# ---------------------------------------------------------------------------
# Trigger Analysis
# ---------------------------------------------------------------------------
st.markdown("---")
analyze_clicked = st.button("🔍 Analyze Resume against Job Description", type="primary", use_container_width=True)

if analyze_clicked:
    if not uploaded_file:
        st.warning("⚠️ Please upload a PDF resume before starting the analysis.")
    elif not jd_input or not jd_input.strip():
        st.warning("⚠️ Please paste a Job Description before starting the analysis.")
    else:
        # Step 1: Extract Text from PDF
        with st.spinner("Extracting text from resume PDF..."):
            try:
                resume_text = extract_text_from_pdf(uploaded_file)
            except ValueError as ve:
                st.error(f"❌ PDF Extraction Error: {ve}")
                resume_text = None
            except Exception as e:
                st.error(f"❌ Unexpected error while reading PDF: {e}")
                resume_text = None

        # Step 2: Run Two-Stage LLM Evaluation
        if resume_text:
            with st.spinner("Running 2-stage prompt chain (Stage 1: Extraction ➔ Stage 2: Evaluation)..."):
                try:
                    result: ResumeAnalysisResult = analyze_resume(
                        resume_text=resume_text,
                        jd_text=jd_input,
                    )
                    st.session_state["analysis_result"] = result
                except ValueError as ve:
                    st.error(f"❌ Input Validation Error: {ve}")
                except RuntimeError as re_err:
                    st.error(f"❌ Analysis Service Error: {re_err}")
                except Exception as exc:
                    st.error(f"❌ An unexpected error occurred: {exc}")

# ---------------------------------------------------------------------------
# Display Results
# ---------------------------------------------------------------------------
if "analysis_result" in st.session_state:
    result: ResumeAnalysisResult = st.session_state["analysis_result"]

    st.markdown("---")
    st.header("📊 Analysis & Evaluation Results")

    # Match Score Card
    score_col, explanation_col = st.columns([1, 2], gap="large")

    with score_col:
        st.subheader("Match Score")
        score_val = result.match_score
        st.metric(label="Heuristic Fit Score (out of 100)", value=f"{score_val} / 100")
        st.progress(score_val / 100.0)

        if score_val >= 75:
            st.success("Strong alignment with core requirements.")
        elif score_val >= 50:
            st.warning("Moderate alignment; key skills or experience missing.")
        else:
            st.error("Low alignment with required qualifications.")

    with explanation_col:
        st.subheader("Score Explanation")
        st.write(result.score_explanation)

    st.markdown("---")

    # Matched vs Missing Skills
    st.subheader("🎯 Skills Gap Analysis")
    col_matched, col_missing = st.columns(2, gap="medium")

    with col_matched:
        st.markdown("### ✅ Matched Skills")
        if result.matched_skills:
            for skill in result.matched_skills:
                st.markdown(f"- **{skill}**")
        else:
            st.markdown("_No direct skill matches found in resume._")

    with col_missing:
        st.markdown("### ⚠️ Missing Skills")
        if result.missing_skills:
            for skill in result.missing_skills:
                st.markdown(f"- **{skill}**")
        else:
            st.markdown("_No missing skills identified._")

    st.markdown("---")

    # Top 3 Priority Fixes
    st.subheader("🚀 Top 3 Priority Fixes")
    for idx, fix in enumerate(result.priority_fixes, start=1):
        st.info(f"**Priority #{idx}:** {fix}")

    st.markdown("---")

    # Suggested Bullet Improvements
    st.subheader("✍️ Suggested Improved Bullet Points")
    st.caption(
        "Rewritten using action-oriented verbs and JD keywords. "
        "Placeholders like `[X]%` or `[Metric]` indicate where the candidate must insert their own verified numbers."
    )

    if result.improved_bullets:
        for idx, bullet in enumerate(result.improved_bullets, start=1):
            with st.expander(f"Bullet #{idx}: {bullet.original_bullet[:60]}..."):
                st.markdown(f"**Original Bullet:**")
                st.code(bullet.original_bullet, language=None)
                st.markdown(f"**Suggested Rewrite:**")
                st.markdown(f"> *{bullet.suggested_bullet}*")
                st.markdown(f"**Rationale:** {bullet.rationale}")
    else:
        st.markdown("_No specific bullet rewrites generated._")

    st.markdown("---")

    # Section-wise Feedback
    st.subheader("📑 Section-by-Section Feedback")
    tab_summary, tab_skills, tab_projects, tab_exp, tab_edu = st.tabs(
        ["Summary", "Skills", "Projects", "Experience", "Education"]
    )

    with tab_summary:
        st.write(result.section_feedback.summary)
    with tab_skills:
        st.write(result.section_feedback.skills)
    with tab_projects:
        st.write(result.section_feedback.projects)
    with tab_exp:
        st.write(result.section_feedback.experience)
    with tab_edu:
        st.write(result.section_feedback.education)

    st.markdown("---")

    # Resume Weaknesses
    st.subheader("🔍 Resume Weaknesses & Improvement Gaps")
    if result.weaknesses:
        for weakness in result.weaknesses:
            st.markdown(f"- {weakness}")
    else:
        st.markdown("_No critical weaknesses identified._")
